//------------------------------------以下为SPI配置程序------------------------------------------
//SPI 特殊功能寄存器
sfr SPSTAT=0xCD;   //SPI状态寄存器
sfr SPCTL =0xCE;   //SPI控制寄存器
sfr SPDAT =0xCF;   //SPI数据寄存器

#define	SSIG		1	//1: 忽略SS脚，由MSTR位决定主机还是从机		0: SS脚用于决定主从机。
#define	SPEN		1	//1: 允许SPI，								0：禁止SPI，所有SPI管脚均为普通IO
#define	DORD		1	//1：LSB先发，								0：MSB先发
#define	MSTR		1	//1：设为主机								0：设为从机
#define	CPOL		1	//1: 空闲时SCLK为高电平，					0：空闲时SCLK为低电平
#define	CPHA		1	//1: SCLK前沿驱动,后沿采样    0:SS==0时SCLK前沿采样,后沿驱动
#define	SPR1		0	//SPR1,SPR0   00: fosc/4,     01: fosc/16
#define	SPR0		0	//            10: fosc/64,    11: fosc/128
#define	SPEED_4		0	// fosc/4

void init_spi_disp()   //将硬件SPI初始化成屏所需要的状态(主机,数据LSB在前)
{
ZKCS=1;
SPCTL = (SSIG << 7) + (SPEN << 6) + (DORD << 5) + (MSTR << 4) + (CPOL << 3) + (CPHA << 2) + SPEED_4; // SSIG，SPEN，DORD，MSTR，CPOL，CPHA，SPR1，SPR0。 1110,1100
SPSTAT = 0xC0;   //清除spi中断标志
}
void init_spi_zk()     //将硬件SPI初始化成字库所需要的状态(主机,数据MSB在前)
{CS=1;
SPCTL = 0xdc;
SPSTAT = 0xC0;   //清除spi中断标志
ZKCS=0;
}

unsigned char writebyte(unsigned char dat)   //SPI发送并接收一个数据
{
     SPDAT = dat;      //发送数据
     while(!(SPSTAT & 0x80) );  //等待发送完毕 SPIF = 1
		 SPSTAT = 0xc0;     //清除SPI标志
		 return SPDAT;
} 	
