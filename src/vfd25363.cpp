void init_vfd(void)
{
P1M0=0;
P1M1=0;
P4M1=0;
P4M0=0x10;  //设置P4.4 EN引脚为强推挽状态

init_spi_disp();
CS=0;writebyte(0xaa);CS=1; //vfd指令1,复位
os_wait2(2,2);//等效延时2ms,可自行替换为delay()函数
CS=0;writebyte(0x55);CS=1;  //vfd指令2,显存复位
os_wait2(2,10);//等效延时10ms,可自行替换为delay()函数
CS=0;writebyte(0xcc);writebyte(0x02);writebyte(0x00);CS=1;//vfd指令3 必要初始化
CS=0;writebyte(0xe0); writebyte(0xfc);writebyte(0x3e);writebyte(0x00);
writebyte(0x20);writebyte(0x80);writebyte(0x80);writebyte(0x80);CS=1; //vfd指令4 显示区域设置 行列值为253,63
CS=0;writebyte(0xb1);writebyte(0x20);writebyte(0x3f);writebyte(0x00);writebyte(0x01);CS=1;
CS=0;writebyte(0xd0);writebyte(0x00);writebyte(0xff);writebyte(0x40);CS=1;
CS=0;writebyte(0xa0);writebyte(0x0c);writebyte(0x40);CS=1;//最后一个是亮度值
CS=0;writebyte(0x80);writebyte(0x40);CS=1;	//开始显示
}

